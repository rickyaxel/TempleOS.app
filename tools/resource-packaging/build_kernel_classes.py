#!/usr/bin/env python3
"""Generate shared/runtime/KernelClasses.HC from TempleOS Kernel/KernelA.HH.

Copies the original class definitions that programs touch (CTask, CDC, menus,
controls, ODEs, mouse/keyboard globals...) so field names and meanings match
TempleOS V5.03. Members whose types belong to subsystems that do not exist in
the mobile runtime (heaps, drives, compiler, debugger) are made opaque:
pointers become U8 *, embedded structs become byte arrays.

Usage: build_kernel_classes.py <templeos-iso dir> <out file>
"""
import re, sys

CLASSES = [
    'CQue', 'CD3I32', 'CD2I32', 'CD2I64', 'CD3I64', 'CD2', 'CD3', 'Complex',
    'CDate', 'CDateStruct', 'CColorROPU16', 'CColorROPU32', 'CBGR24', 'CBGR48',
    'CGrSym', 'CDC', 'CWinScroll', 'CViewAngles', 'CTaskSettings', 'CTask',
    'CMsStateGlbls', 'CGridGlbls', 'CKbdStateGlbls', 'CWinMgrGlbls', 'CTextGlbls', 'CCPU',
    'COrder2D3', 'CMass', 'CSpring', 'CMathODE', 'CCtrl', 'CMenuEntry', 'CMenu',
    'CCmpCtrl', 'CAutoCompleteDictGlbls', 'CDocSettings', 'CDocEntryBase', 'CDocEntry', 'CDocBin', 'CDocUndo', 'CEdFileName', 'CDoc',
    'CHash', 'CHashGeneric', 'CHashTable', 'CDbgInfo', 'CHashSrcSym', 'CHashClass', 'CHashFun',
    'CJob', 'CArcCompress', 'CDirEntry', 'CFifoU8', 'CFifoI64', 'CSndData', 'CScrnCastGlbls',
]

BUILTIN = {'U0', 'I0', 'I8', 'U8', 'I16', 'U16', 'I32', 'U32', 'I64', 'U64', 'F64', 'Bool',
           'I8i', 'U8i', 'I16i', 'U16i', 'I32i', 'U32i', 'I64i', 'U64i', 'F64i', 'U0i'}

# Fields the mobile kernel adds (kept at the end so original offsets stay stable)
EXTRA = {
    'CTask': '  CTask *next_task_mobile;\n  I64	kernel_task_id;\n',
}


def strip(s):
    s = re.sub(r'//[^\n]*', '', s)
    s = re.sub(r'#assert[^\n]*\n', '\n', s)
    s = re.sub(r'#help_index[^\n]*\n', '\n', s)
    return s


def find_class(text, name):
    m = re.search(r'^(public\s+)?((?:[IUF](?:8|16|32|64)i?|Bool)\s+)?(class|union)\s+' + re.escape(name) + r'\b[^;{]*\{', text, re.M)
    if not m:
        return None
    i = m.end()
    depth = 1
    while depth:
        if text[i] == '{': depth += 1
        elif text[i] == '}': depth -= 1
        i += 1
    j = text.index(';', i)
    return text[m.start():j + 1]


def main(root, out):
    text = open(f'{root}/Kernel/KernelA.HH', 'rb').read().split(b'\0')[0].decode('latin-1')
    known = set(CLASSES) | BUILTIN
    parts = ['//Generated by tools/resource-packaging/build_kernel_classes.py - do not edit.',
             '//Class layouts from TempleOS V5.03 Kernel/KernelA.HH (public domain, Terry A. Davis).',
             '//Members of unavailable subsystems are opaque.', '']
    for c in CLASSES:
        parts.append(f'extern class {c};')
    parts.append('')
    for c in CLASSES:
        body = find_class(text, c)
        if body is None:
            raise SystemExit(f'class {c} not found')
        body = strip(body)
        # opaque pointer types
        def ptr(m):
            t = m.group(1)
            return m.group(0) if t in known else 'U8' + m.group(2)
        body = re.sub(r'\b([A-Z][A-Za-z0-9_]*)(\s*\*)', ptr, body)
        # embedded structs of unknown types -> byte arrays
        lines = []
        for line in body.split('\n'):
            m = re.match(r'^(\s*)([A-Z][A-Za-z0-9_]*)\s+([a-z_][A-Za-z0-9_]*)\s*;\s*$', line)
            if m and m.group(2) not in known and m.group(2) not in ('public', 'class', 'union'):
                line = f'{m.group(1)}U8 {m.group(3)}[64]; //opaque {m.group(2)}'
            lines.append(line)
        body = '\n'.join(lines)
        if c in EXTRA:
            k = body.rindex('}')
            body = body[:k] + EXTRA[c] + body[k:]
        parts.append(body.strip() + '\n')
    open(out, 'w', encoding='latin-1').write('\n'.join(parts))
    print(f'{out}: {len(CLASSES)} classes')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])

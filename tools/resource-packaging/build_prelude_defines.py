#!/usr/bin/env python3
"""Extract TempleOS #define constants (public domain) for the system prelude.

Reads the original kernel/graphics headers and writes every single-line
`#define` to shared/runtime/PreludeDefines.HC, preserving original values so
programs see exactly the constants TempleOS V5.03 defines.

Usage: build_prelude_defines.py <templeos-iso dir> <out file>

The input is the byte-exact extraction of the official V5.03 ISO
(tools/asset-extraction/extract_templeos_iso.py).
"""
import re, sys

SOURCES = ['Kernel/KernelA.HH', 'Adam/Gr/Gr.HH']
SKIP = {
    # host/hardware-only values that would mislead programs
}

def main(root, out):
    lines = [
        '//Generated by tools/resource-packaging/build_prelude_defines.py',
        '//Source: TempleOS V5.03 (public domain, Terry A. Davis), files extracted',
        '//from the official TempleOS.ISO (sha256 5d0fc944...). Do not edit by hand.',
        '',
    ]
    seen = set()
    for rel in SOURCES:
        text = open(f'{root}/{rel}', 'rb').read().split(b'\0')[0].decode('latin-1')
        lines.append(f'//---- {rel}')
        text = re.sub(r'\\\s*\n\s*', ' ', text)  # join continuation lines
        for raw in text.split('\n'):
            m = re.match(r'^#define\s+([A-Za-z_\x80-\xff][A-Za-z0-9_\x80-\xff]*)(.*)$', raw)
            if not m:
                continue
            name, body = m.group(1), m.group(2)
            body = re.sub(r'//.*$', '', body)
            body = re.sub(r'\$[A-Z][A-Z][^$]*\$', '', body).strip()
            if name in seen or name in SKIP:
                continue
            seen.add(name)
            lines.append(f'#define {name} {body}'.rstrip())
    open(out, 'w', encoding='latin-1').write('\n'.join(lines) + '\n')
    print(f'{out}: {len(seen)} defines')

if __name__ == '__main__':
    main(*sys.argv[1:3])

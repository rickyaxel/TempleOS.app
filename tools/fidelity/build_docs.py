#!/usr/bin/env python3
"""Generates the data-driven parts of docs/fidelity-audit from the audit records.

Inputs (all in the repository):
  shared/program-manifests/catalog.json        the programs both apps ship
  docs/fidelity-audit/data/specs/<id>.json     per-program behavioural specs (source analysis)
  docs/fidelity-audit/data/unported.json       original runnable programs not in the catalog
  docs/fidelity-audit/data/unported_libs.json  original files that are not programs
  docs/fidelity-audit/data/status.json         per-program audit status (evidence, results, fixes)
  docs/fidelity-audit/data/results-intro.md    hand-written part of the test results page
  docs/fidelity-audit/data/scenario-results-{kotlin,swift}.json
                                               ScenarioTest(s) output (build/, .build/scenario-results.json)

Outputs:
  docs/fidelity-audit/TEMPLEOS_ORIGINAL_PROGRAM_INVENTORY.md
  docs/fidelity-audit/TEMPLEOS_PROGRAM_FIDELITY_AUDIT.md
  docs/fidelity-audit/TEMPLEOS_FIDELITY_TEST_RESULTS.md

Usage: python3 tools/fidelity/build_docs.py [--check]
Development tool only; nothing here ships in the apps.
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DOCS = os.path.join(ROOT, 'docs', 'fidelity-audit')
DATA = os.path.join(DOCS, 'data')
ISO_SHA = '5d0fc944e5d89c155c0fc17c148646715bc1db6fa5750c0b913772cfec19ba26'


def load(p, default=None):
    p = os.path.join(ROOT, p) if not os.path.isabs(p) else p
    if not os.path.exists(p):
        return default
    return json.load(open(p, encoding='utf-8'))


def esc(s):
    return str(s if s is not None else '').replace('|', '\\|').replace('\n', ' ').strip()


def short(s, n=160):
    s = esc(s)
    return s if len(s) <= n else s[:n - 1].rstrip() + '…'


def catalog():
    return load('shared/program-manifests/catalog.json')['programs']


def specs():
    out = {}
    d = os.path.join(DATA, 'specs')
    for f in sorted(os.listdir(d)):
        if f.endswith('.json'):
            out[f[:-5]] = json.load(open(os.path.join(d, f), encoding='utf-8'))
    return out


def original_path(p):
    return p['path'].replace('C:/', '/')


STATUS_KEYS = ['source', 'reference', 'swift', 'kotlin', 'input', 'logic', 'visual', 'audio', 'exit', 'tests', 'overall']
STATUS_TITLES = ['Source mapped', 'Behaviour evidence', 'Swift launch', 'Kotlin launch', 'Input', 'Logic',
                 'Visual', 'Audio', 'Exit/restart', 'Regression tests', 'Overall']


def inventory(cat, sp, unported, libs, status):
    L = []
    w = L.append
    shipped = [p for p in cat if p['category'] != 'example']
    examples = [p for p in cat if p['category'] == 'example']
    hidden = [p for p in shipped if p.get('status') == 'unsupported']
    nlibs = sum(len(v) for k, v in libs.items() if not k.startswith('_')) if isinstance(libs, dict) else len(libs)
    w('# TempleOS original program inventory')
    w('')
    w('Generated by `tools/fidelity/build_docs.py` (do not edit by hand). Part of the')
    w('[fidelity audit](README.md).')
    w('')
    w(f'**Original release:** TempleOS V5.03, official ISO (sha256 `{ISO_SHA[:16]}…`), extracted')
    w('byte-for-byte to `reference/templeos-iso/` by `tools/asset-extraction/extract_templeos_iso.py`.')
    w('The VM checked the extractor: TempleOS\'s own `FileRead` returned the same size and the same')
    w('last bytes for two LZW-compressed files (`TEMPLEOS_FIDELITY_TEST_RESULTS.md` §2).')
    w('**Author:** every original program is by Terry A. Davis (public domain); TempleOS has no')
    w('other credited contributors. The 9 *examples* in the catalog were written for this project and')
    w('have no TempleOS original.')
    w('')
    w('## Counts')
    w('')
    w('| | Count |')
    w('|---|---|')
    w(f'| Original runnable programs found | {len(shipped) + len(unported)} |')
    w(f'| In the catalog (both apps ship the same catalog) | {len(shipped)} |')
    w(f'| … listed in the menus | {len(shipped) - len(hidden)} |')
    w(f'| … bundled but hidden (status "unsupported") | {len(hidden)} |')
    w(f'| Not ported (not in the catalog) | {len(unported)} |')
    w(f'| Project-written examples (no original) | {len(examples)} |')
    w(f'| Original files classified as non-runnable (libraries, data, templates) | {nlibs} |')
    w('')
    w('iOS and Android read the same `shared/program-manifests/catalog.json` and the same bundled')
    w('drive, so a program is available on both or on neither.')
    w('')
    w('## 1. Programs in the catalog')
    w('')
    w('| Id | Original path | Entry point | Category | Controls (catalog) | Catalog status | Audit status |')
    w('|---|---|---|---|---|---|---|')
    for p in shipped:
        s = sp.get(p['id'], {})
        st = status.get(p['id'], {})
        files = s.get('original_files') or [original_path(p)]
        w(f"| `{p['id']}` | {esc(', '.join(files))} | {short(s.get('entry_point', ''), 90)} | {esc(p['category'])} | "
          f"{esc(', '.join(p['controls']) or '-')} | {esc(p.get('status'))} | {esc(st.get('overall', 'see audit'))} |")
    w('')
    w('## 2. Project-written examples (no TempleOS original)')
    w('')
    w('| Id | Path | Note |')
    w('|---|---|---|')
    for p in examples:
        w(f"| `{p['id']}` | `{p['path']}` | {esc(p.get('description'))} |")
    w('')
    w('## 3. Original programs not ported')
    w('')
    w('Found by walking the ISO (`Demo/`, `Apps/`, `Misc/`, `Adam/God/`) and `Doc/DemoIndex.DD`.')
    w('"Portability" is the audit\'s verdict for the mobile runtime; most were run once on the Kotlin core')
    w('to check it (`data/unported.json` notes).')
    w('')
    by = {}
    for u in unported:
        by.setdefault(u['portability'], []).append(u)
    w('| Portability | Count |')
    w('|---|---|')
    for k in sorted(by, key=lambda k: -len(by[k])):
        w(f'| {esc(k)} | {len(by[k])} |')
    w('')
    w('| Name | Path | Category | In DemoIndex | Portability | Why |')
    w('|---|---|---|---|---|---|')
    for u in sorted(unported, key=lambda u: u['path']):
        w(f"| {esc(u['name'])} | `{esc(u['path'])}` | {esc(u['category'])} | {'yes' if u.get('in_demo_index') else 'no'} | "
          f"{esc(u['portability'])} | {short(u.get('portability_reason'), 140)} |")
    w('')
    w('## 4. Original files that are not programs')
    w('')
    w('See `data/unported_libs.json` (support modules, data, templates, sprite/song resources).')
    w('')
    return '\n'.join(L)


def audit(cat, sp, status):
    L = []
    w = L.append
    w('# TempleOS program fidelity audit: per-program records')
    w('')
    w('Generated by `tools/fidelity/build_docs.py` from `data/specs/*.json` (source analysis of the')
    w('original HolyC, one file per program) and `data/status.json` (evidence and results). Do not edit')
    w('by hand. Method, evidence levels and fix list: [README](README.md); test runs:')
    w('[TEMPLEOS_FIDELITY_TEST_RESULTS.md](TEMPLEOS_FIDELITY_TEST_RESULTS.md).')
    w('')
    w('Mobile line numbers inside the specs refer to commit 439e398 (before this audit\'s fixes); the')
    w('original-source line numbers are stable.')
    w('')
    w('## Summary')
    w('')
    w('| Program | ' + ' | '.join(STATUS_TITLES) + ' |')
    w('|---|' + '---|' * len(STATUS_TITLES))
    for p in cat:
        if p['category'] == 'example':
            continue
        st = status.get(p['id'], {})
        w(f"| [{esc(p['title'])}](#{p['id'].replace('.', '')}) | " + ' | '.join(esc(st.get(k, 'Unverified')) for k in STATUS_KEYS) + ' |')
    w('')
    for p in cat:
        if p['category'] == 'example':
            continue
        s = sp.get(p['id'], {})
        st = status.get(p['id'], {})
        w(f"## {p['id']}")
        w('')
        w(f"**{esc(p['title'])}** — `{esc(', '.join(s.get('original_files') or [original_path(p)]))}`; "
          f"entry: {esc(s.get('entry_point', ''))}; category: {esc(s.get('category', p['category']))}.")
        w('')
        if s.get('summary'):
            w(esc(s['summary']))
            w('')
        if st:
            w('| ' + ' | '.join(STATUS_TITLES) + ' |')
            w('|' + '---|' * len(STATUS_TITLES))
            w('| ' + ' | '.join(esc(st.get(k, 'Unverified')) for k in STATUS_KEYS) + ' |')
            w('')
            if st.get('devices'):
                w(f"- Devices: {esc(st['devices'])}")
            if st.get('notes'):
                for n in st['notes']:
                    w(f'- {esc(n)}')
            if st.get('devices') or st.get('notes'):
                w('')
        if s.get('inputs'):
            w('**Original inputs** (source-verified):')
            w('')
            for i in s['inputs'][:14]:
                w(f"- {esc(i.get('input'))}: {short(i.get('semantics'), 140)} ({esc(i.get('api'))}; {esc(i.get('held_or_discrete'))}; {esc(i.get('lines'))})")
            if len(s['inputs']) > 14:
                w(f"- … {len(s['inputs']) - 14} more in `data/specs/{p['id']}.json`")
            w('')
        if s.get('exit_paths'):
            w('**Exit paths:** ' + '; '.join(f"{esc(e.get('trigger'))} → {short(e.get('behavior'), 100)}" for e in s['exit_paths'][:5]))
            w('')
        snd = s.get('sound')
        if snd:
            if isinstance(snd, list):
                w('**Sound:** ' + '; '.join(short(x.get('what'), 100) for x in snd[:4] if isinstance(x, dict)))
            else:
                w('**Sound:** ' + short(snd, 200))
            w('')
        iss = s.get('suspected_issues') or []
        res = st.get('issues', {})
        if iss:
            w('**Discrepancies found by the source analysis** (status after this audit):')
            w('')
            w('| Sev. | Discrepancy | Classification | Status |')
            w('|---|---|---|---|')
            for n, i in enumerate(iss):
                w(f"| {esc(i.get('severity', '?'))[:2]} | {short(i.get('title'), 150)} | {short(i.get('classification'), 60)} | "
                  f"{esc(res.get(str(n), 'open'))} |")
            w('')
    return '\n'.join(L)


def results(cat, intro, kres, sres):
    L = []
    w = L.append
    w(intro.rstrip('\n'))
    w('')
    scen = load('shared/fidelity/scenarios.json', {'scenarios': []})['scenarios']
    k = {r['id']: r for r in kres}
    s = {r['id']: r for r in sres}
    titles = {p['id']: p['title'] for p in cat}
    w('## Shared scenarios: per-program results')
    w('')
    w('Generated by `tools/fidelity/build_docs.py` from `shared/fidelity/scenarios.json` and the two runs in')
    w('`data/scenario-results-kotlin.json` / `data/scenario-results-swift.json`. A scenario drives the')
    w('original program with input in virtual time and checks one source-derived value (the "why"')
    w('column of `scenarios.json`). "—" means the scenario was not part of that run.')
    w('')

    def tally(rs):
        c = {}
        for r in rs:
            c[r['status']] = c.get(r['status'], 0) + 1
        return ', '.join(f'{v} {n}' for n, v in sorted(c.items())) or '—'
    sup = [x for x in scen if not x['unsupported']]
    uns = [x for x in scen if x['unsupported']]
    w('| Set | Scenarios | Kotlin | Swift |')
    w('|---|---|---|---|')
    for name, xs in (('programs the apps offer', sup), ('hidden programs (status "unsupported")', uns)):
        w(f"| {name} | {len(xs)} | {tally([k[x['id']] for x in xs if x['id'] in k])} | "
          f"{tally([s[x['id']] for x in xs if x['id'] in s])} |")
    w('')
    diff = [x for x in scen if x['id'] in k and x['id'] in s and k[x['id']]['status'] != s[x['id']]['status']]
    w(f'Platforms disagree on {len(diff)} scenario(s)' + (':' if diff else '.'))
    w('')
    for x in diff:
        w(f"- `{x['id']}` Kotlin {k[x['id']]['status']} ({esc(k[x['id']]['detail'])}), Swift {s[x['id']]['status']} ({esc(s[x['id']]['detail'])})")
    if diff:
        w('')
    bad = [x for x in sup if (x['id'] in k and k[x['id']]['status'] != 'PASS') or (x['id'] in s and s[x['id']]['status'] != 'PASS')]
    w(f'### Not passing on an offered program ({len(bad)})')
    w('')
    if bad:
        w('| Scenario | Name | Kotlin | Swift | Expected (source) |')
        w('|---|---|---|---|---|')
        for x in bad:
            kr, sr = k.get(x['id']), s.get(x['id'])
            w(f"| `{x['id']}` | {esc(x['name'])} | {esc(kr['status'] + ': ' + kr['detail']) if kr else '—'} | "
              f"{esc(sr['status'] + ': ' + sr['detail']) if sr else '—'} | {short(x['why'], 160)} |")
    else:
        w('None.')
    w('')
    w('### Per program')
    w('')
    w('| Program | Scenarios | Kotlin pass | Swift pass |')
    w('|---|---|---|---|')
    by = {}
    for x in scen:
        by.setdefault(x['id'].split('#')[0], []).append(x)
    for pid in sorted(by):
        xs = by[pid]
        kp = sum(1 for x in xs if k.get(x['id'], {}).get('status') == 'PASS')
        sp_ = sum(1 for x in xs if s.get(x['id'], {}).get('status') == 'PASS')
        kn = sum(1 for x in xs if x['id'] in k)
        sn = sum(1 for x in xs if x['id'] in s)
        hid = ' (hidden)' if xs[0]['unsupported'] else ''
        w(f"| {esc(titles.get(pid, pid))}{hid} | {len(xs)} | {kp}/{kn} | {sp_}/{sn} |")
    w('')
    return '\n'.join(L)


def main():
    check = '--check' in sys.argv
    cat = catalog()
    sp = specs()
    unported = load(os.path.join(DATA, 'unported.json'), [])
    libs = load(os.path.join(DATA, 'unported_libs.json'), {})
    status = load(os.path.join(DATA, 'status.json'), {}).get('programs', {})
    outs = {
        'TEMPLEOS_ORIGINAL_PROGRAM_INVENTORY.md': inventory(cat, sp, unported, libs, status),
        'TEMPLEOS_PROGRAM_FIDELITY_AUDIT.md': audit(cat, sp, status),
    }
    intro = os.path.join(DATA, 'results-intro.md')
    if os.path.exists(intro):
        outs['TEMPLEOS_FIDELITY_TEST_RESULTS.md'] = results(
            cat, open(intro, encoding='utf-8').read(),
            load(os.path.join(DATA, 'scenario-results-kotlin.json'), []),
            load(os.path.join(DATA, 'scenario-results-swift.json'), []))
    bad = 0
    for name, text in outs.items():
        path = os.path.join(DOCS, name)
        text = text.rstrip('\n') + '\n'
        if check:
            if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
                print('out of date:', name)
                bad += 1
        else:
            open(path, 'w', encoding='utf-8').write(text)
            print('wrote', name, len(text), 'bytes')
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())

#!/usr/bin/env python3
"""Builds shared/fidelity/scenarios.json from the audit's per-program specs.

Each spec (docs/fidelity-audit/data/specs/<id>.json) holds "kernel" test scenarios written from the
ORIGINAL source: input steps in virtual time and an expected, source-derived invariant. This tool
normalises them into one platform-neutral file that both test runners execute (Kotlin
ScenarioTest, Swift ScenarioTests), so the two apps are checked against the same expectations.

Step forms: ["wait_ms", n] ["key", K] ["key_down", K] ["key_up", K] ["click", x, y] ["rclick", x, y]
            ["drag", x0, y0, x1, y1] ["popup", value] ["menu", "Path/Item"]
  K: a character ("a", " ", "\\n"), CH_ESC / CH_SHIFT_ESC, or a scan code name (SC_CURSOR_UP, ...).
Probe forms: {"global": "path", "op": "<|<=|==|!=|>=|>", "value": number}  (path: a.b[2].c, $main.x)
             {"exited": true|false}

Usage: python3 tools/fidelity/extract_scenarios.py [--check]
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SPECS = os.path.join(ROOT, 'docs', 'fidelity-audit', 'data', 'specs')
OUT = os.path.join(ROOT, 'shared', 'fidelity', 'scenarios.json')
CATALOG = os.path.join(ROOT, 'shared', 'program-manifests', 'catalog.json')
OPS = {'<', '<=', '==', '!=', '>=', '>'}
STEPS = {'wait_ms', 'key', 'key_down', 'key_up', 'click', 'rclick', 'drag', 'popup', 'menu'}
SLOW_MS = 20000


def valid_step(s):
    if not isinstance(s, list) or not s or s[0] not in STEPS:
        return False
    num = lambda v: isinstance(v, (int, float)) and not isinstance(v, bool)
    n = {'wait_ms': 1, 'click': 2, 'rclick': 2, 'drag': 4, 'popup': 1}.get(s[0])
    if n is not None:
        return len(s) == n + 1 and all(num(v) for v in s[1:])
    return len(s) == 2 and isinstance(s[1], str)


def norm_probe(p):
    if not isinstance(p, dict):
        return None
    if 'exited' in p:
        return {'exited': bool(p['exited'])}
    g = p.get('global')
    op = p.get('op')
    v = p.get('value')
    if not isinstance(g, str) or op not in OPS:
        return None
    if isinstance(v, bool):
        v = int(v)
    if not isinstance(v, (int, float)):
        return None
    return {'global': g.strip(), 'op': op, 'value': v}


def main():
    cat = {p['id']: p for p in json.load(open(CATALOG))['programs']}
    out = []
    skipped = 0
    for f in sorted(os.listdir(SPECS)):
        if not f.endswith('.json'):
            continue
        pid = f[:-5]
        prog = cat.get(pid)
        if not prog:
            continue
        spec = json.load(open(os.path.join(SPECS, f), encoding='utf-8'))
        for n, sc in enumerate(spec.get('test_scenarios') or []):
            if sc.get('kind', 'kernel') != 'kernel':
                skipped += 1
                continue
            steps = sc.get('steps') or []
            probe = norm_probe(sc.get('probe'))
            if probe is None or not all(valid_step(s) for s in steps):
                skipped += 1
                continue
            total = sum(s[1] for s in steps if s[0] == 'wait_ms' and isinstance(s[1], (int, float)))
            out.append({
                'id': f'{pid}#{n}',
                'program': prog['path'],
                'name': sc.get('name', ''),
                'steps': steps,
                'expect': probe,
                'why': sc.get('expect', ''),
                'slow': total > SLOW_MS,
                'unsupported': prog.get('status') == 'unsupported',
            })
    data = {
        '$comment': 'Generated by tools/fidelity/extract_scenarios.py from docs/fidelity-audit/data/specs. '
                    'Expected values come from the original TempleOS source (see "why"), not from the apps.',
        'scenarios': out,
    }
    text = json.dumps(data, indent=1, ensure_ascii=False) + '\n'
    if '--check' in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding='utf-8').read() == text
        print('up to date' if ok else 'out of date')
        return 0 if ok else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8').write(text)
    print(f'{len(out)} scenarios ({sum(1 for s in out if s["slow"])} slow, '
          f'{sum(1 for s in out if s["unsupported"])} for unsupported programs), {skipped} skipped')
    return 0


if __name__ == '__main__':
    sys.exit(main())

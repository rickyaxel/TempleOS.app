#!/usr/bin/env python3
"""Documentation attribution audit (docs/fidelity-audit/TEMPLEOS_DOCUMENTATION_ATTRIBUTION_AUDIT.md).

For every file of the bundled C: drive (shared/bundled-fs.index) it checks:
  integrity  the bundled bytes have the sha256 recorded in the index (what the apps trust at run time)
  source     ISO files: byte-identical to reference/templeos-iso (the TempleOS V5.03 extraction), or
             different only by the documented content-moderation edits (resource-packaging/moderation.json);
             TempleOS Mobile files: identical to shared/home-src
  category   the notice the document viewer shows (DocProvenance in both apps), from the same rules

Usage: doc_attribution_audit.py [--out evidence.md]     exit status 1 on any integrity or source error
"""
import hashlib, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'resource-packaging'))
import build_bundled_fs as B  # noqa: E402  (censor, ORIGIN_OVERRIDES)
import moderation  # noqa: E402

TERRY = 'TempleOS V5.03 (public domain, Terry A. Davis)'
DOC_EXT = ('.DD', '.TXT')  # FilesApp opens these in the document viewer


def category(origin):
    if origin == TERRY: return 'A', 'original'
    if origin.startswith(TERRY + '; modified:'): return 'C', 'adapted'
    if origin == 'TempleOS Mobile': return 'M', 'mobile'
    return 'I', 'included'


def main():
    out = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else None
    rows, errors = [], []
    for line in open(os.path.join(ROOT, 'shared', 'bundled-fs.index'), encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if f[0] != 'F': continue
        rel, size, sha, origin = f[1], int(f[2]), f[3], f[4]
        data = open(os.path.join(ROOT, 'shared', 'bundled-fs', rel), 'rb').read()
        if hashlib.sha256(data).hexdigest() != sha or len(data) != size:
            errors.append(f'{rel}: bundled bytes do not match the index')
        cat, notice = category(origin)
        if origin == 'TempleOS Mobile':
            src = os.path.join(ROOT, 'shared', 'home-src', rel)
            check = 'identical to shared/home-src' if os.path.exists(src) and open(src, 'rb').read() == data else 'MISSING SOURCE'
        else:
            iso_path = os.path.join(ROOT, 'reference', 'templeos-iso', rel)
            iso = open(iso_path, 'rb').read() if os.path.exists(iso_path) else None
            if iso is None:
                check = 'NOT ON THE ISO'
            elif iso == data:
                check = 'byte-identical to the ISO'
            else:
                censored, changed = B.censor(rel, iso)
                if changed and censored == data:
                    ids = ', '.join(e['id'] for e in moderation.load()[1][rel])
                    check = f'ISO with moderation edits {ids} (moderation.json)'
                else:
                    check = 'DIFFERS FROM THE ISO'
            if cat == 'C' and 'moderation edits' not in check: errors.append(f'{rel}: marked modified but {check}')
            if cat == 'A' and check != 'byte-identical to the ISO': errors.append(f'{rel}: category A but {check}')
        if check.isupper() or check.startswith('DIFFERS') or check.startswith('NOT ') or check.startswith('MISSING'):
            errors.append(f'{rel}: {check}')
        rows.append((rel, cat, notice, origin, check, sha))
    docs = [r for r in rows if r[0].upper().endswith(DOC_EXT)]
    counts = {}
    for r in docs: counts[r[1]] = counts.get(r[1], 0) + 1
    md = ['# Documentation attribution evidence', '',
          'Generated by `tools/provenance/doc_attribution_audit.py`. Every bundled file was checked; this table lists the '
          f'{len(docs)} documents the viewer opens (`.DD`, `.TXT`). Categories: A original (Terry A. Davis, unchanged), '
          'C adapted (Terry\'s text with offensive content censored or redacted, moderation.json), I included third-party text, M written for TempleOS Mobile.', '',
          f'All bundled files: {len(rows)}. Integrity and source errors: {len(errors)}.', '',
          '| Category | Documents |', '|---|---|'] + [f'| {k} | {v} |' for k, v in sorted(counts.items())] + ['',
          '| Document | Category | Notice | Recorded origin | Check against source | sha256 |', '|---|---|---|---|---|---|']
    for rel, cat, notice, origin, check, sha in sorted(docs):
        md.append(f'| `{rel}` | {cat} | {notice} | {origin} | {check} | `{sha[:16]}…` |')
    if out:
        open(out, 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    print(f'{len(rows)} files, {len(docs)} documents: ' + ', '.join(f'{k} {v}' for k, v in sorted(counts.items())) + f'; {len(errors)} errors')
    for e in errors: print('ERROR', e)
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())

#!/usr/bin/env python3
"""Writes the platform language declarations from shared/runtime/l10n/locales.json.

  Android  temple_os_kotlin/app/src/main/res/xml/locales_config.xml (android:localeConfig:
           the per-app language list in system Settings, Android 13+)
  iOS      CFBundleLocalizations in temple_os_swift/App/TempleOSMobile/Info.plist (the
           per-app language list in iOS Settings; strings come from the shared catalogs)

and the apps' name (manifest `app_name`, README "Names"), never translated:
  Android  app_name in temple_os_kotlin/app/src/main/res/values/strings.xml (the launcher
           label, through android:label="@string/app_name"; no values-* copies)
  iOS      CFBundleDisplayName in the same Info.plist (the label under the icon; no
           InfoPlist.strings). Bundle id, executable and package names are not touched.

The app's own resolver (docs/localization.md) maps whatever tag the system reports back to
one of the 89 locales, so platform tags only need to name each language the system offers.
Usage: gen_platform.py [--check]   (--check: exit 1 if a generated file is out of date)
"""
import json, os, plistlib, sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MANIFEST = os.path.join(ROOT, 'shared/runtime/l10n/locales.json')
ANDROID = os.path.join(ROOT, 'temple_os_kotlin/app/src/main/res/xml/locales_config.xml')
STRINGS = os.path.join(ROOT, 'temple_os_kotlin/app/src/main/res/values/strings.xml')
IOS = os.path.join(ROOT, 'temple_os_swift/App/TempleOSMobile/Info.plist')
# system tags for locales whose manifest id is not what the OS lists
ANDROID_TAG = {'no-NO': 'nb-NO'}
HEADER = ('<!--\n  TempleOS Mobile Classic: fully offline. No URL schemes, no document types,\n'
          '  no file sharing, no network usage descriptions: nothing can import programs\n'
          '  or data into the app, and the app requests no permissions.\n-->\n')
IOS_TAG = {'no-NO': 'nb', 'zh-CN': 'zh-Hans', 'zh-TW': 'zh-Hant'}


def main():
    manifest = json.load(open(MANIFEST, encoding='utf-8'))
    ids = [l['id'] for l in manifest['locales']]
    name = manifest['app_name']
    strings = ('<?xml version="1.0" encoding="utf-8"?>\n'
               '<!-- Generated by tools/l10n/gen_platform.py from app_name in shared/runtime/l10n/locales.json. -->\n'
               '<resources>\n'
               f'    <string name="app_name" translatable="false">{escape(name)}</string>\n'
               '</resources>\n')
    android = ('<?xml version="1.0" encoding="utf-8"?>\n'
               '<!-- Generated by tools/l10n/gen_platform.py from shared/runtime/l10n/locales.json. -->\n'
               '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
               + ''.join(f'    <locale android:name="{ANDROID_TAG.get(i, i)}" />\n' for i in ids)
               + '</locale-config>\n')
    with open(IOS, 'rb') as f:
        plist = plistlib.load(f)
    plist['CFBundleDevelopmentRegion'] = 'en'
    plist['CFBundleDisplayName'] = name
    plist['CFBundleLocalizations'] = [IOS_TAG.get(i, i) for i in ids]
    ios = plistlib.dumps(plist, sort_keys=True).decode('utf-8').replace('<plist version="1.0">', HEADER + '<plist version="1.0">', 1)
    stale = []
    for path, text in ((ANDROID, android), (STRINGS, strings), (IOS, ios)):
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if '--check' not in sys.argv:
                open(path, 'w', encoding='utf-8').write(text)
    print(f'{len(ids)} locales; ' + (('out of date: ' if '--check' in sys.argv else 'wrote: ') + ', '.join(stale) if stale else 'up to date'))
    sys.exit(1 if stale and '--check' in sys.argv else 0)


if __name__ == '__main__':
    main()

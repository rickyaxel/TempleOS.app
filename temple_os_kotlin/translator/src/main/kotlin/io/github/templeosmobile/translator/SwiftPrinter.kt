package io.github.templeosmobile.translator

/** Prints a [ModuleModel] as a Swift source file (Pure Swift mode). */
class SwiftPrinter(private val m: ModuleModel, private val preludeClass: String) {
    private val sb = StringBuilder()
    private var ind = 0

    private fun line(s: String = "") {
        if (s.isEmpty()) { sb.append('\n'); return }
        repeat(ind) { sb.append("    ") }
        sb.append(s).append('\n')
    }

    private inline fun indent(block: () -> Unit) { ind++; try { block() } finally { ind-- } }

    fun print(): String {
        line("// GENERATED by the TempleOS HolyC-to-native translator (temple_os_kotlin/translator). Do not edit.")
        line("// Source: ${m.source}")
        line("// Source sha256: ${m.sourceHash}")
        line("// The program logic is Terry A. Davis' TempleOS V5.03 HolyC, translated to Swift; comments give the original lines.")
        line("// swiftlint:disable all")
        line()
        line("import Foundation")
        line("import TempleCore")
        line()
        line("public final class ${m.className}: NativeModule {")
        indent {
            if (!m.isPrelude) line("public let P: $preludeClass")
            for (n in m.natives) line("public let n_${Lowerer.ident(n)}: Int")
            for (f in m.fields) line("/** ${f.comment.replace("*/", "* /")} */ public var ${f.name}: Int64 = 0")
            line()
            val ps = if (m.isPrelude) "_ rt: NativeRuntime" else "_ rt: NativeRuntime, _ P: $preludeClass"
            line(if (m.isPrelude) "public override init($ps) {" else "public init($ps) {")
            indent {
                if (!m.isPrelude) line("self.P = P")
                for (n in m.natives) line("n_${Lowerer.ident(n)} = rt.vm.natives.find(\"${esc(n)}\")!.index")
                line("super.init(rt)")
            }
            line("}")
            line()
            printBind()
            for (fn in m.functions) { line(); printFunction(fn) }
            line()
            printDispatch()
        }
        line("}")
        return sb.toString()
    }

    private fun esc(s: String): String {
        val o = StringBuilder()
        for (c in s) when {
            c == '\\' -> o.append("\\\\")
            c == '"' -> o.append("\\\"")
            c.code < 32 || c.code > 126 -> o.append("\\u{%x}".format(c.code))
            else -> o.append(c)
        }
        return o.toString()
    }

    private fun printBind() {
        line("public override func bind(_ unit: Int, _ seg: Segment) throws {")
        indent {
            val byUnit = m.fields.groupBy { it.unit }.toSortedMap()
            line("switch unit {")
            for ((u, fs) in byUnit) {
                line("case $u:")
                indent { for (f in fs) line("${f.name} = try seg.a(0x${Integer.toHexString(f.buildAddr)})") }
            }
            line("default: break")
            line("}")
        }
        line("}")
    }

    private fun printDispatch() {
        val fns = m.functions.sortedBy { it.ref.index }
        line("public override func dispatch(_ t: HTask, _ index: Int, _ base: Int, _ n: Int) throws -> Int64 {")
        indent {
            line("let st = t.st")
            line("switch index {")
            for (fn in fns) {
                val r = fn.ref
                val args = ArrayList<String>()
                args.add("t")
                for ((i, k) in r.params.withIndex()) {
                    val w = "(n > $i ? st[base + $i] : 0)"
                    args.add(if (k == K.F) "d($w)" else w)
                }
                if (r.varargs) { args.add("base + ${r.params.size}"); args.add("max(n - ${r.params.size}, 0)") }
                val call = "try ${r.name}(${args.joinToString(", ")})"
                line("case ${r.index}: " + when (r.ret) { null -> "$call; return 0"; K.F -> "return bits($call)"; else -> "return $call" })
            }
            line("default: throw VmFault(Vm.BAD_CALL, \"call of undefined function #\\(index)\")")
            line("}")
        }
        line("}")
        line()
        line("private static let DEFINED: Set<Int> = [${fns.joinToString(", ") { it.ref.index.toString() }}]")
        line("private static let NAMES: [Int: String] = [${if (fns.isEmpty()) ":" else fns.joinToString(", ") { "${it.ref.index}: \"${esc(it.holyName)}\"" }}]")
        line("private static let FILES: [String] = [${fileIndex.keys.joinToString(", ") { "\"" + esc(it) + "\"" }}]")
        line("public override var files: [String] { ${m.className}.FILES }")
        line("public override func defines(_ index: Int) -> Bool { ${m.className}.DEFINED.contains(index) }")
        line("public override func nameOf(_ index: Int) -> String? { ${m.className}.NAMES[index] }")
    }

    // ------------------------------------------------------------ functions

    private var cur: IrFunction? = null
    private var lastPos: String? = null

    private fun printFunction(fn: IrFunction) {
        cur = fn
        lastPos = null
        val r = fn.ref
        val ps = ArrayList<String>()
        ps.add("_ t: HTask")
        for ((i, k) in r.params.withIndex()) ps.add("_ a$i: ${sw(k)}")
        if (r.varargs) { ps.add("_ vaBase: Int"); ps.add("_ vaN: Int") }
        val ret = when (r.ret) { null -> ""; else -> " -> ${sw(r.ret)}" }
        line("/// HolyC ${fn.holyName} (${fn.file.substringAfterLast('/')}:${fn.line})")
        line("${if (r.ret != null) "@discardableResult " else ""}public final func ${r.name}(${ps.joinToString(", ")}) throws$ret {")
        indent {
          // the current HolyC line, for fault messages as the VM gives them ("Fn (file:line)")
          line("var ln = 0")
          line("do {")
          indent {
            line("try enter(t)")
            if (fn.frameSize > 0 || r.varargs) {
                line("let msp0 = t.msp")
                line(if (r.varargs) "let fp = try frame(t, ${fn.frameSize} + vaN * 8)" else "let fp = try frame(t, ${fn.frameSize})")
            }
            for ((i, p) in fn.params.withIndex()) line("var ${p.name}: ${sw(p.k)} = a$i")
            for ((pi, off) in fn.paramSpills) {
                val p = fn.params[pi]
                line(if (p.k == K.F) "try st8(fp &+ $off, bits(${p.name}))" else "try st8(fp &+ $off, ${p.name})")
            }
            if (r.varargs) {
                line("vaCopy(t, fp &+ ${fn.frameSize}, vaBase, vaN)")
                if (fn.argc != null) line("var argc: Int64 = Int64(vaN)") else line("try st8(fp &+ ${fn.argcOff}, Int64(vaN))")
                if (fn.argv != null) line("var argv: Int64 = fp &+ ${fn.frameSize}") else line("try st8(fp &+ ${fn.argvOff}, fp &+ ${fn.frameSize})")
            }
            for (v in fn.locals) line("var ${v.name}: ${sw(v.k)} = ${zero(v.k)}")
            stmts(fn.body)
            epilogue(0)
            line(when (r.ret) { null -> "return"; K.F -> "return 0.0"; else -> "return 0" })
          }
          line("} catch let e as VmFault { throw locate(e, \"${esc(fn.holyName)}\", ln) }")
        }
        line("}")
    }

    /** Source files named by line markers (`fileIndex << 20 | line`). */
    private val fileIndex = LinkedHashMap<String, Int>()

    private fun sw(k: K) = when (k) { K.I -> "Int64"; K.F -> "Double"; K.B -> "Bool" }
    private fun zero(k: K) = when (k) { K.I -> "0"; K.F -> "0.0"; K.B -> "false" }

    private fun epilogue(tries: Int) {
        val fn = cur!!
        if (tries > 0) line("t.hCount -= $tries")
        if (fn.frameSize > 0 || fn.ref.varargs) line("t.msp = msp0")
        line("t.depth -= 1")
    }

    private fun pos(s: S) {
        val p = s.pos ?: return
        val k = "${p.file.substringAfterLast('/')}:${p.line}"
        if (k != lastPos) {
            val fi = fileIndex.getOrPut(p.file) { fileIndex.size }
            line("ln = ${(fi shl 20) or (p.line and 0xFFFFF)} // $k")
            lastPos = k
        }
    }

    private fun stmts(list: List<S>) { for (s in list) stmt(s) }

    /** `try ` when evaluating [x] can throw (checked loads, division). */
    private fun tr(vararg xs: X?): String = if (xs.any { it != null && throws(Fold.x(it)) }) "try " else ""

    private fun throws(x: X): Boolean = when (x) {
        is XLoad, is XLoadF -> true
        is XOp -> x.op in setOf(Op.DIVS, Op.DIVU, Op.MODS, Op.MODU) || throws(x.a) || (x.b != null && throws(x.b))
        else -> false
    }

    private fun stmt(s: S) {
        pos(s)
        when (s) {
            is SDecl -> line("${if (s.v.mutable) "var" else "let"} ${s.v.name}: ${sw(s.v.k)} = ${s.init?.let { tr(it) + e(it) } ?: zero(s.v.k)}")
            is SSet -> line("${s.v.name} = ${tr(s.x)}${e(s.x)}")
            is SStore -> line("try st${s.w}(${e(s.a)}, ${e(s.x)})")
            is SEval -> line("${tr(s.x)}eval(${e(s.x)})")
            is SCopy -> line("try copy(${e(s.dst)}, ${e(s.src)}, ${s.n})")
            is SCall -> call(s)
            is SIf -> {
                line("if ${tr(s.c)}${e(s.c)} {")
                indent { stmts(s.t) }
                if (s.f != null && s.f.isNotEmpty()) { line("} else {"); indent { stmts(s.f) } }
                line("}")
            }
            is SLoop -> loop(s)
            is SBlock -> { line("${s.label}: do {"); indent { stmts(s.body) }; line("}") }
            is SRetryLoop -> { line("${s.label}: while true {"); indent { stmts(s.body); line("break ${s.label}") }; line("}") }
            is SBreak -> line("break ${s.label}")
            is SContinue -> line("continue ${s.label}")
            is STick -> line("try tick(t)")
            is SHandlers -> line("t.hCount += ${s.delta}")
            is SReturn -> {
                val r = cur!!.ref.ret
                val x = s.x?.let { coerce(it, r ?: K.I) }
                // the value first: evaluating it may fault before the frame is released, as in the VM
                if (r != null && x != null && !trivialX(x)) { val rv = "rv${tmp++}"; line("let $rv: ${sw(r)} = ${tr(x)}${e(x)}"); epilogue(s.tries); line("return $rv") }
                else {
                    epilogue(s.tries)
                    line(when {
                        r == null -> "return"
                        x == null -> if (r == K.F) "return 0.0" else "return 0"
                        else -> "return ${e(x)}"
                    })
                }
            }
            is STry -> {
                val h = "h${s.id}"
                line("let ${h}sp = t.sp, ${h}msp = t.msp, ${h}d = t.depth, ${h}c = t.hCount")
                line("t.hCount = ${h}c + 1")
                line("do {")
                indent { stmts(s.body); line("t.hCount = ${h}c") }
                line("} catch {")
                indent {
                    line("try caught(t, error)")
                    line("t.sp = ${h}sp; t.msp = ${h}msp; t.depth = ${h}d; t.hCount = ${h}c")
                    stmts(s.handler)
                    line("try endCatch(t)")
                }
                line("}")
            }
            is SWhen -> {
                line("switch ${tr(s.x)}${e(s.x)} {")
                for (a in s.arms) {
                    val conds = a.ranges.joinToString(", ") { r -> if (r.first == r.last) lit(r.first) else "${lit(r.first)}...${lit(r.last)}" }
                    line("case $conds:")
                    indent { if (a.body.isEmpty()) line("break") else stmts(a.body) }
                }
                line("default:")
                indent { val d = s.dflt; if (d.isNullOrEmpty()) line("break") else stmts(d) }
                line("}")
            }
            is SMachine -> machine(s)
            is SGoto -> {
                line("${s.stateVar.name} = ${s.target}")
                if (s.tick) line("try tick(t)")
                line("continue ${s.machine}")
            }
            is SRegionEnter -> {
                val r = "rg${s.region.id}"
                line("${r}sp = t.sp; ${r}msp = t.msp; ${r}d = t.depth; ${r}c = t.hCount; t.hCount = ${r}c + 1")
            }
            is SEndCatch -> line("try endCatch(t)")
        }
    }

    private fun trivialX(x: X) = x is XI || x is XF || x is XVar || x is XB

    private fun coerce(x: X, k: K): X = when {
        x.k == k -> x
        k == K.F -> XOp(Op.BITS2F, if (x.k == K.B) XOp(Op.B2I, x) else x)
        x.k == K.F -> XOp(Op.F2BITS, x)
        x.k == K.B -> XOp(Op.B2I, x)
        else -> x
    }

    private fun loop(s: SLoop) {
        val simpleHead = !s.doWhile && s.pre.isEmpty()
        if (simpleHead && s.cond != null) line("${s.label}: while ${tr(s.cond)}${e(s.cond)} {")
        else line("${s.label}: while true {")
        indent {
            if (!s.doWhile && !simpleHead) {
                stmts(s.pre)
                if (s.cond != null) line("if !(${tr(s.cond)}${e(s.cond)}) { break ${s.label} }")
            }
            if (s.cont != null) { line("${s.cont}: do {"); indent { stmts(s.body) }; line("}") } else stmts(s.body)
            if (s.doWhile) {
                stmts(s.pre)
                if (s.cond != null) line("if !(${tr(s.cond)}${e(s.cond)}) { break ${s.label} }")
            }
            stmts(s.post)
            line("try tick(t)")
        }
        line("}")
    }

    private fun machine(s: SMachine) {
        line("var ${s.stateVar.name} = 0")
        for (r in s.regions) line("var rg${r.id}sp = 0, rg${r.id}msp = 0, rg${r.id}d = 0, rg${r.id}c = 0")
        line("${s.label}: while true {")
        indent {
            val hasRegions = s.regions.isNotEmpty()
            if (hasRegions) line("do {")
            indent {
                line("switch ${s.stateVar.name} {")
                for (b in s.blocks) {
                    line("case ${b.id}:")
                    indent { if (b.body.isEmpty()) line("break") else stmts(b.body) }
                }
                line("default: fatalError(\"bad state\")")
                line("}")
            }
            if (hasRegions) {
                line("} catch {")
                indent {
                    line("switch ${s.stateVar.name} {")
                    for (r in s.regions) {
                        val ids = s.blocks.filter { it.region == r.id }.map { it.id }
                        if (ids.isEmpty()) continue
                        line("case ${ids.joinToString(", ")}:")
                        indent {
                            line("try caught(t, error)")
                            line("t.sp = rg${r.id}sp; t.msp = rg${r.id}msp; t.depth = rg${r.id}d; t.hCount = rg${r.id}c")
                            line("${s.stateVar.name} = ${r.handler}")
                        }
                    }
                    line("default: throw error")
                    line("}")
                }
                line("}")
            }
        }
        line("}")
    }

    private var tmp = 0

    private fun call(s: SCall) {
        if (s.tick) line("try tick(t)")
        val res = s.result
        val c = s.callee
        val expr: String = when (c) {
            is CDirect -> {
                val args = ArrayList<String>()
                args.add("t")
                s.args.forEach { args.add(e(it)) }
                if (c.fn.varargs) {
                    val vb = "vb${tmp++}"
                    line("let $vb = ${push(s.extra)}")
                    args.add(vb); args.add(s.extra.size.toString())
                    val call = "try ${c.fn.name}(${args.joinToString(", ")})"
                    if (res != null) line("let ${res.name}: ${sw(res.k)} = ${conv(call, c.fn.ret, res.k)}") else line(if (c.fn.ret != null) "_ = $call" else call)
                    line("t.sp = $vb")
                    return
                }
                conv("try ${c.fn.name}(${args.joinToString(", ")})", c.fn.ret, res?.k)
            }
            is CNative -> {
                if (c.index < 0) "try undefined(\"${esc(c.name.removePrefix("\$undefined:"))}\")"
                else conv("try nat(t, n_${Lowerer.ident(c.name)}, ${push(s.args + s.extra)})", K.I, res?.k, word = true)
            }
            is CPtr -> conv("try ptr(t, ${e(c.fp)}, ${push(s.args + s.extra)})", K.I, res?.k, word = true)
        }
        if (res != null) line("let ${res.name}: ${sw(res.k)} = $expr")
        else {
            val returnsValue = when (c) { is CDirect -> c.fn.ret != null; else -> true }
            line(if (returnsValue) "_ = $expr" else expr)
        }
    }

    private fun conv(call: String, from: K?, to: K?, word: Boolean = false): String {
        if (to == null) return call
        if (word) return if (to == K.F) "d($call)" else call
        if (from == null || from == to) return call
        return if (to == K.F) "d($call)" else "bits($call)"
    }

    private fun push(args: List<X>): String = when (args.size) {
        0 -> "push0(t)"
        1 -> "try push1(t, ${e(args[0])})"
        2 -> "try push2(t, ${e(args[0])}, ${e(args[1])})"
        3 -> "try push3(t, ${e(args[0])}, ${e(args[1])}, ${e(args[2])})"
        4 -> "try push4(t, ${e(args[0])}, ${e(args[1])}, ${e(args[2])}, ${e(args[3])})"
        else -> "try push(t, ${args.joinToString(", ") { e(it) }})"
    }

    // ------------------------------------------------------------ expressions

    private fun lit(v: Long): String = if (v == Long.MIN_VALUE) "Int64.min" else "$v"

    private fun flit(bits: Long): String {
        val d = java.lang.Double.longBitsToDouble(bits)
        return when {
            d.isNaN() -> "d(${lit(bits)})"
            d == Double.POSITIVE_INFINITY -> "Double.infinity"
            d == Double.NEGATIVE_INFINITY -> "(-Double.infinity)"
            else -> {
                val s = d.toString()
                if (java.lang.Double.parseDouble(s).toRawBits() == bits) (if (s.startsWith("-")) "($s)" else s) else "d(${lit(bits)})"
            }
        }
    }

    private fun e(x0: X): String = p(Fold.x(x0))

    private fun p(x: X): String = when (x) {
        is XI -> if (x.v < 0) "(${lit(x.v)})" else lit(x.v)
        is XF -> flit(x.bits)
        is XB -> x.v.toString()
        is XVar -> x.v.name
        is XGlob -> x.name
        is XStr -> x.name
        is XBin -> x.name
        is XFp -> if (x.off == 0) "fp" else "(fp &+ ${x.off})"
        is XNatPtr -> "(Program.FPTR_NATIVE | Int64(n_${Lowerer.ident(x.name)}))"
        is XLoad -> when (x.w) {
            1 -> if (x.signed) "ld1s(${p(x.a)})" else "ld1u(${p(x.a)})"
            2 -> if (x.signed) "ld2s(${p(x.a)})" else "ld2u(${p(x.a)})"
            4 -> if (x.signed) "ld4s(${p(x.a)})" else "ld4u(${p(x.a)})"
            else -> "ld8(${p(x.a)})"
        }
        is XLoadF -> "ldf(${p(x.a)})"
        is XOp -> op(x)
    }

    private fun op(x: XOp): String {
        val a = x.a
        val b = x.b
        return when (x.op) {
            Op.ADD -> "(${p(a)} &+ ${p(b!!)})"
            Op.SUB -> "(${p(a)} &- ${p(b!!)})"
            Op.MUL -> "(${p(a)} &* ${p(b!!)})"
            Op.AND -> "(${p(a)} & ${p(b!!)})"
            Op.OR -> "(${p(a)} | ${p(b!!)})"
            Op.XOR -> "(${p(a)} ^ ${p(b!!)})"
            Op.SHL -> if (b is XI) "(${p(a)} &<< ${b.v and 63})" else "shl(${p(a)}, ${p(b!!)})"
            Op.SHRS -> if (b is XI) "(${p(a)} &>> ${b.v and 63})" else "shr(${p(a)}, ${p(b!!)})"
            Op.SHRU -> "ushr(${p(a)}, ${p(b!!)})"
            Op.DIVS -> "divs(${p(a)}, ${p(b!!)})"
            Op.DIVU -> "divu(${p(a)}, ${p(b!!)})"
            Op.MODS -> "mods(${p(a)}, ${p(b!!)})"
            Op.MODU -> "modu(${p(a)}, ${p(b!!)})"
            Op.POWI -> "ipow(${p(a)}, ${p(b!!)})"
            Op.EQ, Op.FEQ -> "(${p(a)} == ${p(b!!)})"
            Op.NE, Op.FNE -> "(${p(a)} != ${p(b!!)})"
            Op.LTS, Op.FLT -> "(${p(a)} < ${p(b!!)})"
            Op.LES, Op.FLE -> "(${p(a)} <= ${p(b!!)})"
            Op.GTS, Op.FGT -> "(${p(a)} > ${p(b!!)})"
            Op.GES, Op.FGE -> "(${p(a)} >= ${p(b!!)})"
            Op.LTU -> "ltu(${p(a)}, ${p(b!!)})"
            Op.LEU -> "leu(${p(a)}, ${p(b!!)})"
            Op.GTU -> "gtu(${p(a)}, ${p(b!!)})"
            Op.GEU -> "geu(${p(a)}, ${p(b!!)})"
            Op.FADD -> "(${p(a)} + ${p(b!!)})"
            Op.FSUB -> "(${p(a)} - ${p(b!!)})"
            Op.FMUL -> "(${p(a)} * ${p(b!!)})"
            Op.FDIV -> "(${p(a)} / ${p(b!!)})"
            Op.FMOD -> "fmod(${p(a)}, ${p(b!!)})"
            Op.FPOW -> "fpow(${p(a)}, ${p(b!!)})"
            Op.NEG -> "(0 &- ${p(a)})"
            Op.COM -> "(~${p(a)})"
            Op.SX1 -> "sx1(${p(a)})"
            Op.SX2 -> "sx2(${p(a)})"
            Op.SX4 -> "sx4(${p(a)})"
            Op.ZX1 -> "(${p(a)} & 0xFF)"
            Op.ZX2 -> "(${p(a)} & 0xFFFF)"
            Op.ZX4 -> "(${p(a)} & 0xFFFFFFFF)"
            Op.FNEG -> "(-${p(a)})"
            Op.I2F -> "Double(${p(a)})"
            Op.U2F -> "u2f(${p(a)})"
            Op.F2I -> "f2i(${p(a)})"
            Op.BITS2F -> "d(${p(a)})"
            Op.F2BITS -> "bits(${p(a)})"
            Op.B2I -> "b2i(${p(a)})"
            Op.I2B -> "(${p(a)} != 0)"
            Op.F2B -> "(${p(a)} != 0.0)"
            Op.BNOT -> "!${p(a)}"
            Op.BAND -> "(${p(a)} && ${p(b!!)})"
            Op.BOR -> "(${p(a)} || ${p(b!!)})"
            Op.BXOR -> "(${p(a)} != ${p(b!!)})"
        }
    }
}

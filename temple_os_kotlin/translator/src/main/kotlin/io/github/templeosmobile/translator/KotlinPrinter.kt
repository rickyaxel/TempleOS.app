package io.github.templeosmobile.translator

/** Prints a [ModuleModel] as a Kotlin source file (Pure Kotlin mode). */
class KotlinPrinter(private val m: ModuleModel, private val pkg: String, private val preludeClass: String) {
    private val sb = StringBuilder()
    private var ind = 0

    private fun line(s: String = "") {
        if (s.isEmpty()) { sb.append('\n'); return }
        repeat(ind) { sb.append("    ") }
        sb.append(s).append('\n')
    }

    private inline fun indent(block: () -> Unit) { ind++; try { block() } finally { ind-- } }

    fun print(): String {
        line("// GENERATED by the TempleOS HolyC-to-native translator (temple_os_kotlin/translator). Do not edit.")
        line("// Source: ${m.source}")
        line("// Source sha256: ${m.sourceHash}")
        line("// The program logic is Terry A. Davis' TempleOS V5.03 HolyC, translated to Kotlin; comments give the original lines.")
        line("@file:Suppress(\"UNUSED_VARIABLE\", \"UNUSED_VALUE\", \"VARIABLE_WITH_REDUNDANT_INITIALIZER\", \"UNREACHABLE_CODE\", \"UNUSED_PARAMETER\", \"NAME_SHADOWING\", \"LocalVariableName\", \"FunctionName\", \"PropertyName\", \"ClassName\", \"KotlinConstantConditions\", \"UNUSED_EXPRESSION\", \"CanBeVal\", \"RedundantExplicitType\", \"unused\", \"ReplaceWithOperatorAssignment\", \"LiftReturnOrAssignment\", \"CascadeIf\", \"ControlFlowWithEmptyBody\", \"UNUSED_ANONYMOUS_PARAMETER\", \"SENSELESS_COMPARISON\", \"USELESS_IS_CHECK\", \"WRONG_ANNOTATION_TARGET\", \"REDUNDANT_ELSE_IN_WHEN\", \"IntroduceWhenSubject\")")
        line()
        line("package $pkg")
        line()
        line("import io.github.templeosmobile.core.holyc.*")
        line("import io.github.templeosmobile.core.purenative.*")
        line()
        val ctor = if (m.isPrelude) "rt: NativeRuntime" else "rt: NativeRuntime, @JvmField val P: $preludeClass"
        line("class ${m.className}($ctor) : NativeModule(rt) {")
        indent {
            for (n in m.natives) line("@JvmField val n_${Lowerer.ident(n)} = rt.vm.natives.find(\"$n\")!!.index")
            line()
            for (f in m.fields.sortedBy { it.name.length * 0 }) line("/** ${f.comment.replace("*/", "* /")} */ @JvmField var ${f.name}: Long = 0L")
            line()
            printBind()
            for (fn in m.functions) { line(); printFunction(fn) }
            line()
            printDispatch()
        }
        line("}")
        return sb.toString()
    }

    private fun printBind() {
        line("override fun bind(unit: Int, seg: Segment) {")
        indent {
            val byUnit = m.fields.groupBy { it.unit }.toSortedMap()
            if (byUnit.isEmpty()) { line("return"); }
            else {
                line("when (unit) {")
                indent {
                    for ((u, fs) in byUnit) {
                        line("$u -> {")
                        indent { for (f in fs) line("${f.name} = seg.a(0x${Integer.toHexString(f.buildAddr)})") }
                        line("}")
                    }
                }
                line("}")
            }
        }
        line("}")
    }

    private fun printDispatch() {
        val fns = m.functions.sortedBy { it.ref.index }
        line("override fun dispatch(t: Task, index: Int, base: Int, n: Int): Long {")
        indent {
            line("val st = t.st")
            line("return when (index) {")
            indent {
                for (fn in fns) {
                    val r = fn.ref
                    val args = ArrayList<String>()
                    args.add("t")
                    for ((i, k) in r.params.withIndex()) {
                        val w = "(if (n > $i) st[base + $i] else 0L)"
                        args.add(if (k == K.F) "f($w)" else w)
                    }
                    if (r.varargs) { args.add("base + ${r.params.size}"); args.add("maxOf(n - ${r.params.size}, 0)") }
                    val call = "${r.name}(${args.joinToString(", ")})"
                    line("${r.index} -> " + when (r.ret) { null -> "{ $call; 0L }"; K.F -> "bits($call)"; else -> call })
                }
                line("else -> throw VmFault(Vm.BAD_CALL, \"call of undefined function #\$index\")")
            }
            line("}")
        }
        line("}")
        line()
        line("override fun defines(index: Int): Boolean = java.util.Arrays.binarySearch(DEFINED, index) >= 0")
        line()
        line("override fun nameOf(index: Int): String? = java.util.Arrays.binarySearch(DEFINED, index).let { if (it >= 0) NAMES[it] else null }")
        line()
        line("override val files: Array<String> get() = FILES")
        line()
        line("companion object {")
        indent {
            line("private val DEFINED = intArrayOf(${fns.joinToString(", ") { it.ref.index.toString() }})")
            line("private val NAMES = arrayOf(${fns.joinToString(", ") { "\"" + esc(it.holyName) + "\"" }})")
            line("private val FILES = arrayOf<String>(${fileIndex.keys.joinToString(", ") { "\"" + esc(it) + "\"" }})")
        }
        line("}")
    }

    private fun esc(s: String) = s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

    // ------------------------------------------------------------ functions

    private var cur: IrFunction? = null
    private var lastPos: String? = null

    private fun printFunction(fn: IrFunction) {
        cur = fn
        lastPos = null
        val r = fn.ref
        val ps = ArrayList<String>()
        ps.add("t: Task")
        for ((i, k) in r.params.withIndex()) ps.add("a$i: ${kt(k)}")
        if (r.varargs) { ps.add("vaBase: Int"); ps.add("vaN: Int") }
        val ret = when (r.ret) { null -> ""; else -> ": ${kt(r.ret)}" }
        line("/** HolyC ${fn.holyName} (${fn.file.substringAfterLast('/')}:${fn.line}) */")
        line("fun ${r.name}(${ps.joinToString(", ")})$ret {")
        indent {
          // the current HolyC line, for fault messages as the VM gives them ("Fn (file:line)")
          line("var ln = 0")
          line("try {")
          indent {
            line("enter(t)")
            if (fn.frameSize > 0 || r.varargs) {
                line("val msp0 = t.msp")
                line(if (r.varargs) "val fp = frame(t, ${fn.frameSize} + vaN * 8)" else "val fp = frame(t, ${fn.frameSize})")
            }
            for ((i, p) in fn.params.withIndex()) line("var ${p.name}: ${kt(p.k)} = a$i")
            for ((pi, off) in fn.paramSpills) {
                val p = fn.params[pi]
                line(if (p.k == K.F) "st8(fp + $off, bits(${p.name}))" else "st8(fp + $off, ${p.name})")
            }
            if (r.varargs) {
                line("vaCopy(t, fp + ${fn.frameSize}, vaBase, vaN)")
                if (fn.argc != null) line("var argc: Long = vaN.toLong()") else line("st8(fp + ${fn.argcOff}, vaN.toLong())")
                if (fn.argv != null) line("var argv: Long = fp + ${fn.frameSize}") else line("st8(fp + ${fn.argvOff}, fp + ${fn.frameSize})")
            }
            for (v in fn.locals) line("var ${v.name}: ${kt(v.k)} = ${zero(v.k)}")
            stmts(fn.body)
            // the VM's implicit return
            epilogue(0)
            line(when (r.ret) { null -> "return"; K.F -> "return 0.0"; else -> "return 0L" })
          }
          line("} catch (e: VmFault) { throw locate(e, \"${esc(fn.holyName)}\", ln) }")
        }
        line("}")
    }

    /** Source files named by line markers (`fileIndex shl 20 or line`). */
    private val fileIndex = LinkedHashMap<String, Int>()

    private fun kt(k: K) = when (k) { K.I -> "Long"; K.F -> "Double"; K.B -> "Boolean" }
    private fun zero(k: K) = when (k) { K.I -> "0L"; K.F -> "0.0"; K.B -> "false" }

    private fun epilogue(tries: Int) {
        val fn = cur!!
        if (tries > 0) line("t.hCount -= $tries")
        if (fn.frameSize > 0 || fn.ref.varargs) line("t.msp = msp0")
        line("t.depth--")
    }

    private fun pos(s: S) {
        val p = s.pos ?: return
        val k = "${p.file.substringAfterLast('/')}:${p.line}"
        if (k != lastPos) {
            val fi = fileIndex.getOrPut(p.file) { fileIndex.size }
            line("ln = ${(fi shl 20) or (p.line and 0xFFFFF)} // $k")
            lastPos = k
        }
    }

    private fun stmts(list: List<S>) { for (s in list) stmt(s) }

    private fun stmt(s: S) {
        pos(s)
        when (s) {
            is SDecl -> line("${if (s.v.mutable) "var" else "val"} ${s.v.name}: ${kt(s.v.k)} = ${s.init?.let { e(it) } ?: zero(s.v.k)}")
            is SSet -> line("${s.v.name} = ${e(s.x)}")
            is SStore -> line("st${s.w}(${e(s.a)}, ${e(s.x)})")
            is SEval -> line("eval(${e(s.x)})")
            is SCopy -> line("copy(${e(s.dst)}, ${e(s.src)}, ${s.n})")
            is SCall -> call(s)
            is SIf -> {
                line("if (${e(s.c)}) {")
                indent { stmts(s.t) }
                if (s.f != null && s.f.isNotEmpty()) { line("} else {"); indent { stmts(s.f) } }
                line("}")
            }
            is SLoop -> loop(s)
            is SBlock -> { line("${s.label}@ do {"); indent { stmts(s.body) }; line("} while (false)") }
            is SRetryLoop -> { line("${s.label}@ while (true) {"); indent { stmts(s.body); line("break@${s.label}") }; line("}") }
            is SBreak -> line("break@${s.label}")
            is SContinue -> line("continue@${s.label}")
            is STick -> line("tick(t)")
            is SHandlers -> line("t.hCount += ${s.delta}")
            is SReturn -> {
                epilogue(s.tries)
                val r = cur!!.ref.ret
                line(when {
                    r == null -> "return"
                    s.x == null -> if (r == K.F) "return 0.0" else "return 0L"
                    else -> "return ${e(coerce(s.x, r))}"
                })
            }
            is STry -> {
                val h = "h${s.id}"
                line("val ${h}sp = t.sp; val ${h}msp = t.msp; val ${h}d = t.depth; val ${h}c = t.hCount")
                line("t.hCount = ${h}c + 1")
                line("try {")
                indent { stmts(s.body); line("t.hCount = ${h}c") }
                line("} catch (e${s.id}: RuntimeException) {")
                indent {
                    line("caught(t, e${s.id})")
                    line("t.sp = ${h}sp; t.msp = ${h}msp; t.depth = ${h}d; t.hCount = ${h}c")
                    stmts(s.handler)
                    line("endCatch(t)")
                }
                line("}")
            }
            is SWhen -> {
                line("when (${e(s.x)}) {")
                indent {
                    for (a in s.arms) {
                        val conds = a.ranges.joinToString(", ") { r -> if (r.first == r.last) lit(r.first) else "in ${lit(r.first)}..${lit(r.last)}" }
                        line("$conds -> {")
                        indent { stmts(a.body) }
                        line("}")
                    }
                    line("else -> {")
                    indent { s.dflt?.let { stmts(it) } }
                    line("}")
                }
                line("}")
            }
            is SMachine -> machine(s)
            is SGoto -> {
                line("${s.stateVar.name} = ${s.target}")
                if (s.tick) line("tick(t)")
                line("continue@${s.machine}")
            }
            is SRegionEnter -> {
                val r = "rg${s.region.id}"
                line("${r}sp = t.sp; ${r}msp = t.msp; ${r}d = t.depth; ${r}c = t.hCount; t.hCount = ${r}c + 1")
            }
            is SEndCatch -> line("endCatch(t)")
        }
    }

    private fun coerce(x: X, k: K): X = when {
        x.k == k -> x
        k == K.F -> XOp(Op.BITS2F, if (x.k == K.B) XOp(Op.B2I, x) else x)
        x.k == K.F -> XOp(Op.F2BITS, x)
        x.k == K.B -> XOp(Op.B2I, x)
        else -> x
    }

    private fun loop(s: SLoop) {
        val simpleHead = !s.doWhile && s.pre.isEmpty()
        if (simpleHead && s.cond != null) line("${s.label}@ while (${e(s.cond)}) {")
        else line("${s.label}@ while (true) {")
        indent {
            if (!s.doWhile && !simpleHead) {
                stmts(s.pre)
                if (s.cond != null) line("if (!(${e(s.cond)})) break@${s.label}")
            }
            if (s.cont != null) { line("${s.cont}@ do {"); indent { stmts(s.body) }; line("} while (false)") } else stmts(s.body)
            if (s.doWhile) {
                stmts(s.pre)
                if (s.cond != null) line("if (!(${e(s.cond)})) break@${s.label}")
            }
            stmts(s.post)
            line("tick(t)")
        }
        line("}")
    }

    private fun machine(s: SMachine) {
        line("var ${s.stateVar.name} = 0")
        for (r in s.regions) line("var rg${r.id}sp = 0; var rg${r.id}msp = 0; var rg${r.id}d = 0; var rg${r.id}c = 0")
        line("${s.label}@ while (true) {")
        indent {
            if (s.regions.isNotEmpty()) line("try {")
            indent {
                line("when (${s.stateVar.name}) {")
                indent {
                    for (b in s.blocks) {
                        line("${b.id} -> {")
                        indent { stmts(b.body) }
                        line("}")
                    }
                    line("else -> throw IllegalStateException(\"bad state\")")
                }
                line("}")
            }
            if (s.regions.isNotEmpty()) {
                line("} catch (em: RuntimeException) {")
                indent {
                    line("when (${s.stateVar.name}) {")
                    indent {
                        for (r in s.regions) {
                            val ids = s.blocks.filter { it.region == r.id }.map { it.id }
                            if (ids.isEmpty()) continue
                            line("${ids.joinToString(", ")} -> {")
                            indent {
                                line("caught(t, em)")
                                line("t.sp = rg${r.id}sp; t.msp = rg${r.id}msp; t.depth = rg${r.id}d; t.hCount = rg${r.id}c")
                                line("${s.stateVar.name} = ${r.handler}")
                            }
                            line("}")
                        }
                        line("else -> throw em")
                    }
                    line("}")
                }
                line("}")
            }
        }
        line("}")
    }

    private fun call(s: SCall) {
        if (s.tick) line("tick(t)")
        val res = s.result
        val c = s.callee
        val expr: String = when (c) {
            is CDirect -> {
                val args = ArrayList<String>()
                args.add("t")
                s.args.forEach { args.add(e(it)) }
                if (c.fn.varargs) {
                    val vb = "vb${tmp++}"
                    line("val $vb = ${push(s.extra)}")
                    args.add(vb); args.add(s.extra.size.toString())
                    val call = "${c.fn.name}(${args.joinToString(", ")})"
                    // the extra words stay pushed until the callee has copied them
                    if (res != null) line("val ${res.name}: ${kt(res.k)} = ${conv(call, c.fn.ret, res.k)}") else line(call)
                    line("t.sp = $vb")
                    return
                }
                conv("${c.fn.name}(${args.joinToString(", ")})", c.fn.ret, res?.k)
            }
            is CNative -> {
                if (c.index < 0) "undefined(\"${esc(c.name.removePrefix("\$undefined:"))}\")"
                else conv("nat(t, n_${Lowerer.ident(c.name)}, ${push(s.args + s.extra)})", K.I, res?.k, word = true)
            }
            is CPtr -> conv("ptr(t, ${e(c.fp)}, ${push(s.args + s.extra)})", K.I, res?.k, word = true)
        }
        if (res != null) line("val ${res.name}: ${kt(res.k)} = $expr") else line(expr)
    }

    private var tmp = 0

    /** Converts a call result of kind [from] to the wanted kind [to] (words from natives/pointers). */
    private fun conv(call: String, from: K?, to: K?, word: Boolean = false): String {
        if (to == null) return call
        if (word) return if (to == K.F) "f($call)" else call
        if (from == null) return call
        if (from == to) return call
        return if (to == K.F) "f($call)" else "bits($call)"
    }

    private fun push(args: List<X>): String = when (args.size) {
        0 -> "push0(t)"
        1 -> "push1(t, ${e(args[0])})"
        2 -> "push2(t, ${e(args[0])}, ${e(args[1])})"
        3 -> "push3(t, ${e(args[0])}, ${e(args[1])}, ${e(args[2])})"
        4 -> "push4(t, ${e(args[0])}, ${e(args[1])}, ${e(args[2])}, ${e(args[3])})"
        else -> "push(t, ${args.joinToString(", ") { e(it) }})"
    }

    // ------------------------------------------------------------ expressions

    private fun lit(v: Long): String = if (v == Long.MIN_VALUE) "Long.MIN_VALUE" else "${v}L"

    private fun flit(bits: Long): String {
        val d = java.lang.Double.longBitsToDouble(bits)
        return when {
            d.isNaN() -> "f(${lit(bits)})"
            d == Double.POSITIVE_INFINITY -> "Double.POSITIVE_INFINITY"
            d == Double.NEGATIVE_INFINITY -> "Double.NEGATIVE_INFINITY"
            else -> {
                val s = d.toString()
                if (java.lang.Double.parseDouble(s).toRawBits() == bits) s else "f(${lit(bits)})"
            }
        }
    }

    /** Expression text (constants folded); parenthesized unless it is atomic. */
    private fun e(x0: X): String = pe(Fold.x(x0))

    private fun pe(x: X): String = when (x) {
        is XI -> lit(x.v)
        is XF -> flit(x.bits)
        is XB -> x.v.toString()
        is XVar -> x.v.name
        is XGlob -> x.name
        is XStr -> x.name
        is XBin -> x.name
        is XFp -> if (x.off == 0) "fp" else "(fp + ${x.off})"
        is XNatPtr -> "(Program.FPTR_NATIVE or n_${Lowerer.ident(x.name)}.toLong())"
        is XLoad -> when (x.w) {
            1 -> if (x.signed) "ld1s(${e(x.a)})" else "ld1u(${e(x.a)})"
            2 -> if (x.signed) "ld2s(${e(x.a)})" else "ld2u(${e(x.a)})"
            4 -> if (x.signed) "ld4s(${e(x.a)})" else "ld4u(${e(x.a)})"
            else -> "ld8(${e(x.a)})"
        }
        is XLoadF -> "ldf(${e(x.a)})"
        is XOp -> op(x)
    }

    private fun op(x: XOp): String {
        val a = x.a
        val b = x.b
        return when (x.op) {
            Op.ADD -> "(${e(a)} + ${e(b!!)})"
            Op.SUB -> "(${e(a)} - ${e(b!!)})"
            Op.MUL -> "(${e(a)} * ${e(b!!)})"
            Op.AND -> "(${e(a)} and ${e(b!!)})"
            Op.OR -> "(${e(a)} or ${e(b!!)})"
            Op.XOR -> "(${e(a)} xor ${e(b!!)})"
            Op.SHL -> "(${e(a)} shl ${shift(b!!)})"
            Op.SHRS -> "(${e(a)} shr ${shift(b!!)})"
            Op.SHRU -> "(${e(a)} ushr ${shift(b!!)})"
            Op.DIVS -> "divs(${e(a)}, ${e(b!!)})"
            Op.DIVU -> "divu(${e(a)}, ${e(b!!)})"
            Op.MODS -> "mods(${e(a)}, ${e(b!!)})"
            Op.MODU -> "modu(${e(a)}, ${e(b!!)})"
            Op.POWI -> "ipow(${e(a)}, ${e(b!!)})"
            Op.EQ, Op.FEQ -> "(${e(a)} == ${e(b!!)})"
            Op.NE, Op.FNE -> "(${e(a)} != ${e(b!!)})"
            Op.LTS, Op.FLT -> "(${e(a)} < ${e(b!!)})"
            Op.LES, Op.FLE -> "(${e(a)} <= ${e(b!!)})"
            Op.GTS, Op.FGT -> "(${e(a)} > ${e(b!!)})"
            Op.GES, Op.FGE -> "(${e(a)} >= ${e(b!!)})"
            Op.LTU -> "ltu(${e(a)}, ${e(b!!)})"
            Op.LEU -> "leu(${e(a)}, ${e(b!!)})"
            Op.GTU -> "gtu(${e(a)}, ${e(b!!)})"
            Op.GEU -> "geu(${e(a)}, ${e(b!!)})"
            Op.FADD -> "(${e(a)} + ${e(b!!)})"
            Op.FSUB -> "(${e(a)} - ${e(b!!)})"
            Op.FMUL -> "(${e(a)} * ${e(b!!)})"
            Op.FDIV -> "(${e(a)} / ${e(b!!)})"
            Op.FMOD -> "(${e(a)} % ${e(b!!)})"
            Op.FPOW -> "fpow(${e(a)}, ${e(b!!)})"
            Op.NEG -> "(-${e(a)})"
            Op.COM -> "${e(a)}.inv()"
            Op.SX1 -> "sx1(${e(a)})"
            Op.SX2 -> "sx2(${e(a)})"
            Op.SX4 -> "sx4(${e(a)})"
            Op.ZX1 -> "(${e(a)} and 0xFFL)"
            Op.ZX2 -> "(${e(a)} and 0xFFFFL)"
            Op.ZX4 -> "(${e(a)} and 0xFFFFFFFFL)"
            Op.FNEG -> "(-${e(a)})"
            Op.I2F -> "${e(a)}.toDouble()"
            Op.U2F -> "u2f(${e(a)})"
            Op.F2I -> "f2i(${e(a)})"
            Op.BITS2F -> "f(${e(a)})"
            Op.F2BITS -> "bits(${e(a)})"
            Op.B2I -> "b2i(${e(a)})"
            Op.I2B -> "(${e(a)} != 0L)"
            Op.F2B -> "(${e(a)} != 0.0)"
            Op.BNOT -> "!${e(a)}"
            Op.BAND -> "(${e(a)} && ${e(b!!)})"
            Op.BOR -> "(${e(a)} || ${e(b!!)})"
            Op.BXOR -> "(${e(a)} != ${e(b!!)})"
        }
    }

    /** Kotlin shifts take an Int count and mask it to 6 bits, like the VM's `shl st[sp].toInt()`. */
    private fun shift(b: X): String = if (b is XI) (b.v.toInt()).toString() else "${e(b)}.toInt()"
}

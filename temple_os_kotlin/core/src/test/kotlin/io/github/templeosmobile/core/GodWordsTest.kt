class GodWordsTest {
    @Suppress("UNCHECKED_CAST")
    private val v = Json.parse(File(SHARED, "test-vectors/god-words/vectors.json").readText()) as Map<String, Any?>
    private val latches = (v["latches"] as List<*>).map { (it as Number).toLong() }
    private val picks = (v["picks"] as List<*>).map { (it as Number).toInt() }
    private val actions = (v["actions"] as List<*>).map { it as String }
    private val reads = (v["reads_after_action"] as List<*>).map { (it as Number).toInt() }

    /** Presses the vectors' button [k] ("ten" = 10 WORDS, "word" = WORD). */
    private fun press(g: GodApp, k: Int) = if (actions[k] == "ten") g.tenWordsButton() else g.wordButton()
    /** Picks made by the first [k] presses. */
    private fun picksAfter(k: Int) = picks.take(actions.take(k).sumOf { if (it == "ten") 10 else 1 })
    private val dir = kotlin.io.path.createTempDirectory("tosm-god").toFile()
    private val env = HeadlessEnv(dir)

    @Before fun english() { L10n.init(env::runtimeFile); L10n.use("en-US") }
    @After fun back() { L10n.use("en-US"); dir.deleteRecursively() }

    /** A God Words window whose timer returns the vectors' latches, counting how often it is read. */
    private class Clock(val values: List<Long>) { var reads = 0; fun next(): Long = values[reads++] }

    private fun god(clock: Clock): Pair<Shell, GodApp> {
        val sh = Shell(env); sh.resize(360, 640)
        val g = GodApp(sh, clock::next)
        sh.open(g); sh.tick()
        return sh to g
    }

    private fun vocab() = GodVocab.tokenize(env.fs.readFile("C:/Adam/God/Vocab.DD")!!)

    @Test fun vocabularyIsSplitAsGodInitSplitsIt() {
        val words = vocab()
        assertEquals((v["count"] as Number).toInt(), words.size)
        assertEquals(7569, words.size)
        assertEquals(v["sha256"], GodVocab.digest(words))
        @Suppress("UNCHECKED_CAST")
        for ((i, w) in v["spot"] as Map<String, String>) assertEquals("entry $i", w, words[i.toInt()])
        // digits, '_' and bytes >= 128 are word characters (Kernel/StrA.HC char_bmp_word); no entry is merged or dropped
        assertEquals("etext00", words[2314]); assertEquals("tcosa10a", words[6587])
        assertEquals(GodVocab.tokenize("ab1_c'd-x\u0000ignored".toByteArray(Charsets.ISO_8859_1)), listOf("ab1_c'd", "x"))
        assertEquals(listOf("caf\u00e9"), GodVocab.tokenize(byteArrayOf(0x63, 0x61, 0x66, 0x82.toByte())))
        // duplicates stay separate entries (no dedup): the bundled list has "delay" twice (5592 is moderation edit VO-5593)
        assertEquals(words.size - 1, words.toSet().size)
        assertEquals(listOf(1625, 5592), words.indices.filter { words[it] == "delay" })
    }

    @Test fun bundledVocabularyMatchesTheIsoExceptTheDocumentedReplacement() {
        val original = File(REFERENCE, "templeos-iso/Adam/God/Vocab.DD")
        assumeTrue("reference/templeos-iso is not on this machine", original.exists())
        val iso = GodVocab.tokenize(original.readBytes())
        val words = vocab()
        assertEquals(iso.size, words.size)
        val diff = iso.indices.filter { iso[it] != words[it] }
        @Suppress("UNCHECKED_CAST")
        assertEquals((v["iso_differs_at"] as Map<String, Any?>).keys.map { it.toInt() }, diff)
        assertEquals(listOf(5592), diff)
        // the original word is identified by its hash, not spelled out (tools/resource-packaging/moderation.json VO-5593)
        assertEquals("158869a97379229b7681efae9d7f9c9214134e836d649ba53477c0c111414d59", sha256Hex(iso[5592].toByteArray()))
        assertEquals("delay", words[5592])
    }

    @Test fun picksFollowGodBitsModuloTheVocabulary() {
        val clock = Clock(latches)
        val (_, g) = god(clock)
        // every button is TempleOS's F7: flush, one latch; GodBits latches again only when the FIFO runs dry
        for (k in actions.indices) {
            press(g, k)
            assertEquals("picks after press $k", picksAfter(k + 1), g.picks)
            assertEquals("timer reads after press $k", reads[k], clock.reads)
        }
        @Suppress("UNCHECKED_CAST")
        val english = v["english"] as List<String>
        assertTrue(g.text().contains(english.take(10).joinToString(" ")))
        assertEquals(10, g.text().lines().first { it.startsWith(english[0]) }.split(' ').size.coerceAtMost(10))
    }

    @Test fun changingTheLanguageShowsTheSamePicksAndDrawsNoBits() {
        val clock = Clock(latches)
        val (sh, g) = god(clock)
        press(g, 0); sh.tick()
        @Suppress("UNCHECKED_CAST")
        val display = v["display"] as Map<String, List<String>>
        for (loc in listOf("es-ES", "fr-FR", "en-US", "ja-JP", "ar", "he-IL", "zh-CN", "ko-KR", "hi-IN", "ru-RU", "th", "am", "es-ES")) {
            sh.settings.language = loc; sh.applyLanguage(); sh.tick()
            assertEquals(loc, L10n.locale?.id)
            assertEquals("no timer reads on a language change ($loc)", reads[0], clock.reads)
            assertEquals(picksAfter(1), g.picks)
            @Suppress("UNCHECKED_CAST")
            val shown = if (loc == "en-US") (v["english"] as List<String>) else display.getValue(loc)
            assertTrue("$loc shows the same ten entries", g.text().contains(shown.take(10).joinToString(" ")))
        }
        // the next press continues exactly as if no language change had happened: rendering consumed nothing
        press(g, 1)
        assertEquals(picksAfter(2), g.picks)
        assertEquals(reads[1], clock.reads)
        assertTrue(g.text().contains(display.getValue("es-ES").subList(10, 20).joinToString(" ")))
    }

    @Test fun languageSwitchesLoadEachVocabularyOnce() {
        val (sh, g) = god(Clock(latches))
        g.tenWordsButton()
        sh.settings.language = "de-DE"; sh.applyLanguage(); sh.tick()
        val n = GodVocab.loads
        repeat(5) { sh.invalidate(); sh.tick(); g.text() }
        assertEquals(n, GodVocab.loads)
        sh.settings.language = "ja-JP"; sh.applyLanguage(); sh.tick()
        assertEquals(n + 1, GodVocab.loads)
    }

    @Test fun everySupportedCatalogHasAValidVocabularyFile() {
        val words = vocab()
        val digest = GodVocab.digest(words)
        @Suppress("UNCHECKED_CAST")
        val m = Json.parse(String(env.runtimeFile("l10n/locales.json")!!, Charsets.UTF_8)) as Map<String, Any?>
        @Suppress("UNCHECKED_CAST")
        val cats = (m["locales"] as List<Map<String, Any?>>).map { it["catalog"] as String }.toSortedSet() - "en"
        assertEquals(72, cats.size)
        val report = StringBuilder()
        var present = 0
        for (c in cats) {
            val t = GodVocab.table(c, digest, words.size, env::runtimeFile)
            assertEquals("$c loads", "ok", t.status)
            present += t.translated
            for (i in words.indices) {
                val s = t.translation(i) ?: continue
                assertTrue("$c $i is NFC", Normalizer.isNormalized(s, Normalizer.Form.NFC))
                assertFalse("$c $i has no placeholder", s.contains("{") || s.contains("TODO") || s.contains('\uFFFD'))
            }
            report.append("$c ${t.translated}/${words.size}\n")
        }
        println("God Words coverage: $present / ${cats.size * words.size}\n$report")
    }

    /** Prints load, generation and redraw costs (docs/fidelity-audit/TEMPLEOS_10_WORDS_VALIDATION.md). */
    @Test fun vocabularyCosts() {
        val words = vocab()
        val digest = GodVocab.digest(words)
        val loads = ArrayList<Double>()
        for (c in listOf("de", "ja", "ar", "zh-Hans", "ru", "hi", "th", "es", "ko", "fr")) {
            if (env.runtimeFile("l10n/vocab/$c.deflate") == null) continue
            GodVocab.table("en", digest, words.size, env::runtimeFile) // drop the cache
            val t0 = System.nanoTime()
            val t = GodVocab.table(c, digest, words.size, env::runtimeFile)
            loads.add((System.nanoTime() - t0) / 1e6)
            assertEquals("ok", t.status)
        }
        val (sh, g) = god(Clock(List(2000) { latches[it % latches.size] + it * 7919L }))
        sh.settings.language = "ja-JP"; sh.applyLanguage(); sh.tick()
        val gen = ArrayList<Double>()
        repeat(20) {
            val t0 = System.nanoTime(); g.tenWordsButton(); sh.invalidate(); sh.tick(); gen.add((System.nanoTime() - t0) / 1e6)
        }
        val switch0 = System.nanoTime()
        sh.settings.language = "ar"; sh.applyLanguage(); sh.tick()
        val switchMs = (System.nanoTime() - switch0) / 1e6
        loads.sort(); gen.sort()
        println("GODWORDS-COST load ms median ${"%.1f".format(loads[loads.size / 2])} max ${"%.1f".format(loads.last())} (${loads.size} catalogs); " +
            "10 WORDS + redraw ms median ${"%.2f".format(gen[gen.size / 2])} max ${"%.2f".format(gen.last())}; language switch with 200 words shown ${"%.1f".format(switchMs)} ms")
        assertTrue(loads.last() < 2000)
    }

    private fun deflate(text: String): ByteArray {
        val bo = ByteArrayOutputStream()
        DeflaterOutputStream(bo, Deflater(9, true)).use { it.write(text.toByteArray(Charsets.UTF_8)) }
        return bo.toByteArray()
    }

    @Test fun brokenOrMismatchedFilesFallBackToEnglishWithoutRerolling() {
        val words = listOf("alpha", "beta", "gamma")
        val digest = GodVocab.digest(words)
        val good = "${GodVocab.FORMAT} count=3 sha256=$digest\nα\n\nγ\u0007\n"
        val files = mutableMapOf<String, ByteArray>()
        val src: (String) -> ByteArray? = { files[it] }
        files["l10n/vocab/xx.deflate"] = deflate(good)
        val t = GodVocab.table("xx", digest, 3, src)
        assertEquals("ok", t.status)
        assertEquals("α", t.translation(0))
        assertNull("empty = not translated", t.translation(1))
        assertNull("control character = invalid", t.translation(2))
        assertNull("index past the end", t.translation(3))
        assertEquals("missing", GodVocab.table("yy", digest, 3, src).status)
        files["l10n/vocab/zz.deflate"] = deflate(good.replace(digest, "0".repeat(64)))
        assertEquals("mismatch", GodVocab.table("zz", digest, 3, src).status)
        files["l10n/vocab/ww.deflate"] = byteArrayOf(1, 2, 3, 4, 5)
        assertEquals("corrupt", GodVocab.table("ww", digest, 3, src).status)
        files["l10n/vocab/vv.deflate"] = deflate("${GodVocab.FORMAT} count=3 sha256=$digest\nα\n")
        assertEquals("corrupt", GodVocab.table("vv", digest, 3, src).status)
        assertEquals("english", GodVocab.table("en", digest, 3, src).status)
    }


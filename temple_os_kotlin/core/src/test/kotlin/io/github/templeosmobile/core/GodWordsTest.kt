    /** Words of the file's text outside DolDoc commands, as the viewer must show them (in order). */
    private fun proseWords(file: String): List<String> {
        val t = textPart(File(SHARED, "bundled-fs/$file").readBytes())
        val plain = StringBuilder()
        var i = 0
        while (i < t.length) {
            if (t[i] == '$') {
                if (i + 1 < t.length && t[i + 1] == '$') { plain.append('$'); i += 2; continue }
                val j = t.indexOf('$', i + 1); if (j < 0) break
                i = j + 1; continue // a command's own text (links, $TX) is not counted: only the prose around it
            }
            plain.append(t[i]); i++
        }
        return letters(plain.toString())
    }

    /** Runs of letters and digits: punctuation next to a link (`"$LK,...$"`) belongs to neither side. */
    private fun letters(s: String) = s.split(Regex("[^\\p{L}\\p{N}]+")).filter { it.isNotEmpty() }

    @Test fun theViewerKeepsTheDocumentsWords() {
        val sh = Shell(env); sh.resize(360, 640)
        for (file in listOf("Doc/HelpIndex.DD", "Doc/Credits.DD", "Adam/God/HSNotes.DD", "Doc/Welcome.DD", "Doc/FAQ.DD")) {
            val d = DocViewerApp(sh, "C:/$file")
            val shown = letters(d.documentText())
            var k = 0
            for (w in proseWords(file)) {
                // in order; a word may be split across a wrapped line only at a space, so each source word is one shown word
                while (k < shown.size && !shown[k].startsWith(w) && !shown[k].endsWith(w)) k++
                assertTrue("$file: '$w' is shown in order", k < shown.size)
                k++
            }
        }
    }

    @Test fun aboutPageAcknowledgesTheModernAdditions() {
        for (loc in listOf("en-US", "es-ES", "ja-JP", "ar")) {
            val sh = Shell(env); sh.resize(360, 640)
            sh.settings.language = loc; sh.applyLanguage()
            sh.open(AboutApp(sh)); sh.tick()
            val text = sh.accessibilityNodes().joinToString("\n") { it.label }
            for (k in listOf("about.additions.title", "about.additions.words", "about.additions.modern", "about.intro.creator", "about.credits.templeos"))
                assertTrue("$loc shows $k", text.contains(L10n.tr(k)))
            if (loc != "en-US") assertNotEquals("$loc is translated", L10n.tr("about.additions.modern"), englishOf("about.additions.modern"))
        }
        val en = englishOf("about.additions.modern") + englishOf("about.additions.words")
        assertTrue(en.contains("were not part of Terry A. Davis' original TempleOS"))
        assertFalse(en.contains("endorse") || en.contains("official TempleOS"))
    }

    private fun englishOf(key: String): String {
        @Suppress("UNCHECKED_CAST")
        val m = Json.parse(File(SHARED, "runtime/l10n/en.json").readText()) as Map<String, Any?>
        return m[key] as String
    }

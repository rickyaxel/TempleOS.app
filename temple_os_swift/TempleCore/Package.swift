// swift-tools-version:6.0
// TempleCore: the platform-neutral TempleOS Mobile runtime for iOS (HolyC
// compiler + VM, kernel, virtual filesystem, desktop shell and apps). A
// line-for-line port of temple_os_kotlin/core; no UIKit and no networking,
// so it builds and tests on macOS with `swift test`.
import PackageDescription

let package = Package(
    name: "TempleCore",
    platforms: [.iOS(.v16), .macOS(.v13)],
    products: [
        .library(name: "TempleCore", targets: ["TempleCore"]),
        // Pure Swift mode: the bundled HolyC programs translated ahead of time to Swift
        // (Sources/PureSwift/Generated is generated by temple_os_kotlin/translator; do not edit).
        .library(name: "PureSwift", targets: ["PureSwift"]),
    ],
    targets: [
        // C11 atomics for the native engine's task handoff (Swift's Atomic needs iOS 18)
        .target(name: "CTempleAtomics", path: "Sources/CTempleAtomics"),
        .target(
            name: "TempleCore",
            dependencies: ["CTempleAtomics"],
            path: "Sources/TempleCore",
            swiftSettings: [.swiftLanguageMode(.v5), .unsafeFlags(["-enforce-exclusivity=unchecked"])]
        ),
        .target(
            name: "PureSwift",
            dependencies: ["TempleCore"],
            path: "Sources/PureSwift",
            swiftSettings: [.swiftLanguageMode(.v5), .unsafeFlags(["-enforce-exclusivity=unchecked", "-suppress-warnings"])]
        ),
        .testTarget(
            name: "PureSwiftTests",
            dependencies: ["TempleCore", "PureSwift"],
            path: "Tests/PureSwiftTests",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .testTarget(
            name: "TempleCoreTests",
            dependencies: ["TempleCore"],
            path: "Tests/TempleCoreTests",
            exclude: ["fdlibm-vectors"],
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
    ]
)
